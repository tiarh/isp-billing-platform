<?php

namespace App\Console\Commands;

use App\Services\RouterPppoeCredentialService;
use Illuminate\Console\Command;
use RuntimeException;
use Throwable;

class RoutersPasswordReconcile extends Command
{
    protected $signature = 'routers:password-reconcile
                            {snapshot : Path to a masked snapshot JSON generated by routers:password-audit}
                            {--apply : Enable the approval-controlled database update}
                            {--approval= : Exact approval phrase}
                            {--backup-manifest= : Existing backup manifest path}';

    protected $description = 'Approval-controlled PPPoE password reconciliation; MikroTik remains source of truth';

    public function handle(RouterPppoeCredentialService $credentials): int
    {
        try {
            $snapshot = $this->readSnapshot((string) $this->argument('snapshot'));
            $runId = (string) ($snapshot['run_id'] ?? '');

            if (! (bool) $this->option('apply')) {
                $this->warn('NOT_RUN: --apply tidak diberikan; tidak ada database/router/queue/WA write.');
                $this->line('Approval yang diperlukan: APPROVE DB PASSWORD RECONCILIATION '.$runId);

                return self::SUCCESS;
            }

            $result = $credentials->reconcileApproved(
                $snapshot,
                (string) $this->option('approval'),
                trim((string) $this->option('backup-manifest'))
            );
            $this->line(json_encode($result, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR));

            return self::SUCCESS;
        } catch (Throwable $e) {
            $this->error('BLOCKED: '.$this->safeMessage($e));

            return self::FAILURE;
        }
    }

    /** @return array<string, mixed> */
    private function readSnapshot(string $path): array
    {
        if ($path === '' || ! is_file($path)) {
            throw new RuntimeException('Masked snapshot tidak ditemukan.');
        }
        $decoded = json_decode((string) file_get_contents($path), true);
        if (! is_array($decoded) || ($decoded['mode'] ?? '') !== 'READ_ONLY' || ($decoded['writes'] ?? true) !== false) {
            throw new RuntimeException('Snapshot tidak valid atau bukan hasil READ_ONLY.');
        }

        return $decoded;
    }

    private function safeMessage(Throwable $e): string
    {
        $message = trim($e->getMessage());
        if ($message === '') {
            return 'rekonsiliasi diblokir.';
        }

        return preg_replace('/(?i)(password|pass|secret)\s*[:=]\s*\S+/', '$1=[REDACTED]', $message) ?: 'rekonsiliasi diblokir.';
    }
}
